"""Prepare compact, read-only timelines for occupations without a specialist replay."""
import csv
from collections import Counter, defaultdict
from pathlib import Path
from typing import NamedTuple

from data.PersonalTimelineSkills import ACTION_ICONS


class Observation(NamedTuple):
    time: int
    skill: str
    name: str
    kind: str
    events: int
    targets: int


def build_personal_timelines(actor):
    """Index the log once, keeping native cast starts and observed direct skill results separate."""
    bld = getattr(actor, "bld", None)
    if bld is None or not getattr(bld, "log", None):
        return {}
    people = bld.info.player
    entries = getattr(actor, "occResult", {})
    counts = Counter(person.name for person in people.values())
    wanted = {key: person.name for key, person in people.items()
              if person.name in entries and counts[person.name] == 1
              and not entries[person.name].get("result", {}).get("replay")}
    if not wanted:
        return {}
    casts = defaultdict(list)
    hits = defaultdict(dict)
    names = {}

    def label(event):
        key = event.full_id.strip('"')
        if key not in names:
            text = bld.info.getSkillName(key)
            names[key] = text if text and text != key else f"技能 {event.id}"
        return names[key]

    for event in bld.log:
        kind = event.dataType
        if kind not in ("Cast", "Skill") or event.caster not in wanted:
            continue
        if not actor.startTime <= event.time <= actor.finalTime:
            continue
        if kind == "Cast":
            casts[event.caster].append(Observation(event.time, str(event.id), label(event), "施放", 1, 0))
            continue
        # Scheme 1 is a direct skill result. ResultType 1 is native reflection.
        # Damage/healing confirms an observed effect only, never a cast or a GCD.
        if event.scheme != 1 or getattr(event, "resultType", None) not in (0, None):
            continue
        if not (event.damage > 0 or event.heal > 0 or event.damageEff > 0 or event.healEff > 0):
            continue
        group = hits[event.caster]
        key = (event.time, str(event.id), event.level)
        if key not in group:
            group[key] = [label(event), 1, event.target]
        else:
            row = group[key]
            row[1] += 1
            if isinstance(row[2], set):
                row[2].add(event.target)
            elif row[2] != event.target:
                row[2] = {row[2], event.target}

    timelines = {}
    for key, person in wanted.items():
        records = casts[key]
        for (time, skill, _level), (name, count, targets) in hits[key].items():
            kind = "招式命中" if skill in ACTION_ICONS else "技能效果"
            n = len(targets) if isinstance(targets, set) else 1
            records.append(Observation(time, skill, name, kind, count, n))
        timelines[person] = sorted(records, key=lambda row: row.time)
    return timelines


def generate_action_icons(root):
    """Rebuild the observed-action display catalogue from the portable formal client evidence."""
    from release.NameGenerator import read_rows

    learned = set()
    for family in ("skill", "skill_mobile"):
        directory = root / "xinfa10009_evidence" / "unpack_result" / "settings" / family / "SkillAutoLearning"
        files = sorted(directory.glob("*.tab"))
        if not files:
            raise ValueError(f"Missing auto-learning tables: {directory}")
        for table in files:
            with table.open(encoding="gb18030", newline="") as source:
                learned.update(row["SkillID"] for row in csv.DictReader(source, delimiter="\t")
                               if row["IsEnableAutoLearning"] == "1")
    icons = {}
    for filename in ("skill.txt", "skill2.txt"):
        for row in read_rows(root/filename, {"SkillID","Show","CanDrag","Name","IconID"}):
            if row["SkillID"] in learned and row["Show"] == row["CanDrag"] == "1" and row["Name"]:
                icons[row["SkillID"]] = row["IconID"]
    return icons


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Rebuild or check the UI timeline action catalogue.")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    icons = generate_action_icons(root/"equip/resources/cangshengtf")
    if args.check:
        if icons != ACTION_ICONS:
            raise SystemExit("Timeline action catalogue differs from formal tables.")
        print(f"Verified {len(icons)} learned, draggable action icons")
    else:
        header = '"""Generated by python -m data.PersonalTimeline from the 10009 client tables."""\n\n'
        pairs = [f"{key!r}: {icons[key]!r}" for key in sorted(icons, key=int)]
        lines = ["    "+", ".join(pairs[i:i+6])+"," for i in range(0,len(pairs),6)]
        (root/"data/PersonalTimelineSkills.py").write_text(
            header+"ACTION_ICONS = {\n"+"\n".join(lines)+"\n}\n", encoding="utf-8")
